# -*- coding: utf-8 -*-
"""БЛОК 8 — УХОД ПЕРЕДНЕГО ПЛАНА МИМО ОБЪЕКТИВА (склейка без склейки).

Камера едет вбок. На её пути вплотную к объективу стоит опора: пока камера
проходит мимо, опора проносится через кадр и на несколько кадров закрывает
его целиком. ПОД ЭТИМ ПРИКРЫТИЕМ место меняется — когда опора уходит, зритель
уже в другом месте, а движение камеры не прервалось. Монтажного стыка нет:
глаз видит не склейку, а что камера «вынесла» его из одного места в другое.

Чем это ценно всем сборщикам: один приём закрывает ПЕРЕХОД между сценами, а
переходы нужны везде. Накрывающим предметом может быть что угодно близкое —
опора, ствол, стена, спина прохожего; требование одно: в самый плотный момент
его проекция должна накрыть кадр целиком, иначе получится не переход, а
мелькание.

Арифметика накрытия (её и надо повторять при внедрении): предмет шириной
`SLAB_W` на удалении `d` от плоскости камеры даёт на экране ширину
`f*SLAB_W/d`. При f=1250, SLAB_W=340 и d=110 это 3863 px против 1920 — кадр
закрыт с запасом вдвое, причём закрыт ровно те 0,3-0,4 с, пока |camx| < 85.
Подмена места делается в середине этого окна, то есть при camx = 0.
"""
import os, sys, math
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from film import (W, H, FPS, new_frame, finish, mix, lerp, clamp, smoother,
                  CREAM, INK)
from skel3d import Cam3, body, draw_body, ground_shadow
from stage3 import grid, box, lamp, haze, depth

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "frames")
DUR = 10.0

BG3   = (10, 12, 18)
EYE_Y, EYE_Z = 205.0, -700.0
TRACK = (-1150.0, 1150.0)        # ход камеры вбок; camx=0 ровно на середине
TILT  = -0.035
HMAN  = 430.0

# накрывающая опора: центр основания, (ширина, высота, глубина)
SLAB_AT  = (0.0, 0.0, EYE_Z + 155.0)
SLAB_SZ  = (340.0, 660.0, 90.0)

fog = lambda col, z: haze(col, z, BG3)
LOOK_DY = TILT*1500.0          # взгляд чуть ниже горизонта, цель на 1500 вперёд

# ---------------------------------------------------------------- два места
# место, из которого уезжаем: тесная улица, свет справа
A = dict(light=(0.40, 0.78, -0.42), road=(46, 60, 88),
         houses=((-1500.0, 520.0, 620.0, 620.0, 700.0), (1540.0, 560.0, 640.0, 700.0, 720.0),
                 (-1620.0, 1560.0, 700.0, 540.0, 740.0), (1600.0, 1600.0, 660.0, 760.0, 700.0),
                 (-300.0, 2600.0, 820.0, 700.0, 760.0), (900.0, 2680.0, 760.0, 580.0, 720.0)),
         lamps=((-640.0, 420.0), (660.0, 440.0), (-520.0, 1500.0), (540.0, 1520.0)),
         people=((-760.0, 300.0, "stand", 24.0, 1.00), (720.0, 360.0, "guard", -20.0, 1.02),
                 (-260.0, 980.0, "stand", 10.0, 0.98), (340.0, 1040.0, "stand", -12.0, 0.99),
                 (-60.0, 1900.0, "guard", 4.0, 0.96)))

# место, в которое приезжаем: площадь шире, свет слева, людей больше
B = dict(light=(-0.46, 0.76, -0.38), road=(40, 66, 82),
         houses=((-2000.0, 1500.0, 760.0, 420.0, 740.0), (2040.0, 1560.0, 720.0, 480.0, 720.0),
                 (-1500.0, 2700.0, 820.0, 760.0, 760.0), (420.0, 2860.0, 900.0, 640.0, 780.0),
                 (1700.0, 2740.0, 780.0, 840.0, 740.0)),
         lamps=((-980.0, 900.0), (980.0, 920.0), (0.0, 2000.0)),
         people=((-1040.0, 520.0, "guard", 30.0, 1.01), (-420.0, 700.0, "stand", 16.0, 0.99),
                 (180.0, 620.0, "dodge", -8.0, 1.03), (840.0, 760.0, "stand", -26.0, 1.00),
                 (-640.0, 1340.0, "stand", 12.0, 0.97), (520.0, 1420.0, "guard", -14.0, 0.98),
                 (-120.0, 2200.0, "stand", 2.0, 0.95)))


def draw_place(im, d, cam, pl):
    light = pl["light"]
    grid(d, cam, mix(pl["road"], BG3, 0.26), step=400.0, x_half=2800.0,
         z0=-760.0, z1=3600.0, alpha=165)

    for x, z, w, h, dp in sorted(pl["houses"],
                                 key=lambda b: -depth(cam, (b[0], b[3]/2, b[1]))):
        box(d, cam, (x, 0.0, z), (w, h, dp), (64, 72, 96), light, fog=fog,
            seed=int(x + z), ink=mix((22, 26, 36), BG3, 0.2))

    stand = []
    for x, z in pl["lamps"]:
        p = np.array([x, 0.0, z])
        stand.append((depth(cam, p + np.array([0.0, 520.0, 0.0])),
                      lambda p=p: lamp(im, d, cam, p, fog=fog)))

    figs = []
    for x, z, pose, yaw, hk in pl["people"]:
        p = np.array([x, 0.0, z])
        figs.append((depth(cam, p + np.array([0.0, HMAN*0.5, 0.0])),
                     body(HMAN*hk, pose, yaw, tuple(p))))
    for _, prims in figs:
        ground_shadow(d, cam, prims, (0, 0, 0), 110)
    for dz, prims in figs:
        stand.append((dz, lambda prims=prims, dz=dz: draw_body(
            im, cam, prims, fog(CREAM, dz), fog(INK, dz), HMAN*0.013,
            light=light, shade=0.58, warm=0.26)))

    for _, fn in sorted(stand, key=lambda s: -s[0]):
        fn()


def frame(i):
    t = i/FPS
    k = smoother(clamp(t/DUR))
    camx = lerp(*TRACK, k)
    eye = (camx, EYE_Y, EYE_Z)
    cam = Cam3(eye, (camx, EYE_Y + LOOK_DY, EYE_Z + 1500.0))

    place = A if camx < 0.0 else B       # подмена ровно в момент накрытия
    im, d = new_frame(BG3 + (255,))
    draw_place(im, d, cam, place)

    # опора — последней, она ближе всего к объективу
    box(d, cam, SLAB_AT, SLAB_SZ, (74, 78, 86), place["light"], fog=fog,
        windows=False, ink=mix((16, 18, 24), BG3, 0.15))

    return finish(im).save(f"{OUT}/f{i:05d}.jpg", quality=94)

