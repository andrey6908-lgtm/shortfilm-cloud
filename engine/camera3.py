"""КАМЕРА, СВЕТ И ОБЪЁМ В КОРОТКОМЕТРАЖКЕ — три приёма лаборатории камеры,
принятые им 01.11.2026, перенесённые в рисовалку короткометражек.

  plane(cam, pan, k)   ПАРАЛЛАКС (блок 1). План на своей глубине едет со
                       своей скоростью: небо почти стоит, дальние дома
                       ползут, тротуар уезжает вровень с шагом.
  figure_light(...)    СВЕТ ПО ФИГУРЕ (блок 3). Фигура рисуется на свой
                       прозрачный слой, сверху кладётся линейный градиент,
                       ПОМНОЖЕННЫЙ НА АЛЬФУ слоя: тёплая вуаль со стороны
                       фонаря и тёмный бок с другой ложатся ровно по телу и
                       ни на пиксель мимо.
  ground_shadow(...)   ТЕНЬ НА ЗЕМЛЕ (блок 4). Пятно под ногами, вытянутое
                       ОТ источника света, прижимает фигуру к тротуару.

Почему не перенесён `skel3d` целиком: там фигура собрана из капсул и шаров в
трёхмерном пространстве, а здесь — плоский рисунок в мировых координатах
кадра. Объём в короткометражке даёт не геометрия, а свет и тень, поэтому
берутся ровно эти два приёма, а облёт 360° остаётся в лаборатории.
"""
import numpy as np
from PIL import Image

from film import Cam, SDraw, SS, soft_ellipse

# Глубины планов уличной сцены: доля, с которой план едет за камерой.
# 1.0 — земля под ногами, 0.0 — бесконечность.
K_SKY, K_FAR, K_NEAR, K_GROUND = 0.06, 0.28, 0.58, 1.0


def plane(cam, pan, k):
    """Камера одного плана. `pan` — сдвиг камеры в мировых единицах."""
    return Cam(cam.s, cam.cx + pan * k, cam.cy)


def figure_light(im, draw_fn, lamp_x, warm=(255, 206, 142), dark=(16, 20, 34),
                 k_warm=0.42, k_dark=0.40):
    """Нарисовать фигуру со светотенью. draw_fn(layer, sdraw) рисует фигуру
    на переданный слой и возвращает то, что вернула рисовалка.

    lamp_x — экранная координата источника света (логические 1920x1080):
    слева от фигуры или справа, от этого зависит, какой бок освещён.
    """
    lay = Image.new("RGBA", im.size, (0, 0, 0, 0))
    info = draw_fn(lay, SDraw(lay, "RGBA"))
    a = lay.split()[3]
    box = a.getbbox()
    if not box:
        return info
    x0, y0, x1, y1 = box
    w, h = x1 - x0, y1 - y0
    # Горизонтальный градиент: 0 у дальнего от фонаря края, 1 у ближнего.
    ramp = np.linspace(0.0, 1.0, w, dtype=np.float32)
    if lamp_x * SS < (x0 + x1) / 2:          # фонарь слева — светлее левый бок
        ramp = ramp[::-1]
    lit = np.tile(ramp, (h, 1))
    am = np.asarray(a.crop(box), dtype=np.float32) / 255.0

    def veil(color, strength, mask):
        rgb = np.zeros((h, w, 4), dtype=np.uint8)
        rgb[..., 0], rgb[..., 1], rgb[..., 2] = color
        rgb[..., 3] = np.clip(mask * am * strength * 255.0, 0, 255).astype(np.uint8)
        lay.alpha_composite(Image.fromarray(rgb, "RGBA"), (x0, y0))

    veil(warm, k_warm, lit ** 1.6)           # освещённый бок
    veil(dark, k_dark, (1.0 - lit) ** 1.5)   # теневой бок
    im.alpha_composite(lay)
    return info


def ground_shadow(im, cam, foot, h, lamp_x, strength=0.58):
    """Пятно под фигурой. `foot` и `lamp_x` — МИРОВЫЕ координаты одного и
    того же плана (земли). Чем дальше фонарь вбок, тем длиннее тень и тем
    сильнее она уходит в противоположную сторону."""
    fx, fy = foot
    off = max(-1.0, min(1.0, (fx - lamp_x) / 620.0))
    sx, sy = cam.p(fx + off * h * 0.22, fy + h * 0.012)
    soft_ellipse(im, sx, sy, cam.r(h * (0.30 + abs(off) * 0.16)),
                 cam.r(h * 0.055), (0, 0, 0), strength, 1.8)
